"""Verify the delivered files and write output/qa-report.md.

    python scripts/verify.py      (needs ffmpeg/ffprobe, opencv-python-headless)

Checks per video: exists & non-empty, resolution, fps, duration, codecs,
audio present, integrated loudness / true peak, and that the QR code decodes
to the exact Google Play URL when read *from the rendered video frame*.
"""
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

import cv2

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "output"
URL = "https://play.google.com/store/apps/details?id=io.github.solimananas.twa"
EXPECT = {
    "zad-al-muslim-hero.mp4": (1920, 1080),
    "zad-al-muslim-reel.mp4": (1080, 1920),
    "zad-al-muslim-square.mp4": (1080, 1080),
}


def probe(path):
    r = subprocess.run(["ffprobe", "-v", "error", "-show_streams", "-show_format", "-of", "json", str(path)],
                       capture_output=True, text=True, check=True)
    return json.loads(r.stdout)


def loudness(path):
    r = subprocess.run(["ffmpeg", "-hide_banner", "-i", str(path), "-af", "ebur128=peak=true", "-f", "null", "-"],
                       capture_output=True, text=True)
    tail = r.stderr[r.stderr.rfind("Summary:"):]
    i = re.search(r"I:\s+(-?[\d.]+) LUFS", tail)
    p = re.search(r"Peak:\s+(-?[\d.]+) dBFS", tail)
    return float(i.group(1)), float(p.group(1))


def qr_from_frame(path, t):
    with tempfile.TemporaryDirectory() as td:
        png = Path(td) / "f.png"
        subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-ss", str(t), "-i", str(path), "-frames:v", "1", str(png)], check=True)
        img = cv2.imread(str(png))
        det = cv2.QRCodeDetector()
        for scale in (1.0, 0.75, 1.5, 0.5):
            im = cv2.resize(img, None, fx=scale, fy=scale, interpolation=cv2.INTER_AREA if scale < 1 else cv2.INTER_CUBIC)
            data, _, _ = det.detectAndDecode(im)
            if data:
                return data
    return ""


def main():
    rows, ok_all = [], True
    for name, (w, h) in EXPECT.items():
        p = OUT / name
        if not p.exists() or p.stat().st_size == 0:
            rows.append(f"| {name} | MISSING | | | | | | | FAIL |")
            ok_all = False
            continue
        info = probe(p)
        v = next(s for s in info["streams"] if s["codec_type"] == "video")
        a = [s for s in info["streams"] if s["codec_type"] == "audio"]
        fps = eval(v["r_frame_rate"])
        dur = float(info["format"]["duration"])
        lufs, peak = loudness(p) if a else (None, None)
        qr = qr_from_frame(p, 44.0)
        checks = [
            (int(v["width"]), int(v["height"])) == (w, h),
            abs(fps - 30) < 0.01,
            40 <= dur <= 45.5,
            v["codec_name"] == "h264",
            bool(a) and a[0]["codec_name"] == "aac",
            qr == URL,
        ]
        ok = all(checks)
        ok_all &= ok
        rows.append(
            f"| {name} | {v['width']}×{v['height']} | {fps:g} fps | {dur:.2f} s | {v['codec_name']} / {a[0]['codec_name'] if a else 'none'} "
            f"| {p.stat().st_size / 1e6:.1f} MB | {lufs} LUFS / {peak} dBFS | {'✅ exact URL' if qr == URL else '❌ ' + (qr or 'no decode')} "
            f"| {'PASS' if ok else 'FAIL'} |")
    report = [
        "# QA report (generated by scripts/verify.py)", "",
        "| File | Resolution | Frame rate | Duration | Video / audio codec | Size | Loudness / peak | QR decoded from frame at 44 s | Result |",
        "|---|---|---|---|---|---|---|---|---|", *rows, "",
        f"Expected QR target: `{URL}`", "",
    ]
    for img in ["zad-al-muslim-poster.png", "zad-al-muslim-poster-vertical.png"]:
        p = OUT / img
        report.append(f"- `{img}`: {'present, ' + str(cv2.imread(str(p)).shape[1::-1]) if p.exists() else 'MISSING'}")
    (OUT / "qa-report.md").write_text("\n".join(report) + "\n")
    print("\n".join(report))
    sys.exit(0 if ok_all else 1)


if __name__ == "__main__":
    main()
