"""Check the Google Play listing assets against Play's published specs and
write output/google-play/ar/spec-check.md.

    python scripts/store-verify.py

Specs: https://support.google.com/googleplay/android-developer/answer/9866151
"""
import json
import subprocess
import sys
from pathlib import Path

from PIL import Image

D = Path(__file__).resolve().parent.parent / "output" / "google-play" / "ar"
rows, ok_all = [], True


def check(name, ok, detail):
    global ok_all
    ok_all &= ok
    rows.append(f"| {name} | {detail} | {'PASS' if ok else 'FAIL'} |")


# app icon: 512×512, 32-bit PNG, ≤ 1024 KB
p = D / "app-icon-512.png"
im = Image.open(p)
check(p.name, im.size == (512, 512) and im.mode == "RGBA" and p.stat().st_size <= 1024 * 1024,
      f"{im.size[0]}×{im.size[1]}, {im.mode} (32-bit), {p.stat().st_size // 1024} KB (≤ 1024 KB)")

# feature graphic: 1024×500, JPEG or 24-bit PNG (no alpha)
p = D / "feature-graphic.png"
im = Image.open(p)
check(p.name, im.size == (1024, 500) and im.mode == "RGB", f"{im.size[0]}×{im.size[1]}, {im.mode} (24-bit, no alpha)")

# phone screenshots: 2–8, 24-bit PNG, 320–3840 px, long ≤ 2× short; ≥ 4 at 1080 px 9:16 for promotion
shots = sorted(D.glob("phone-*.png"))
check("phone screenshots (count)", 2 <= len(shots) <= 8, f"{len(shots)} (2–8; ≥ 4 at 1080×1920 for large-format recommendations)")
for p in shots:
    im = Image.open(p)
    w, h = im.size
    check(p.name, im.mode == "RGB" and 320 <= min(w, h) and max(w, h) <= 3840 and max(w, h) <= 2 * min(w, h) and (w, h) == (1080, 1920),
          f"{w}×{h} (9:16), {im.mode}, {p.stat().st_size // 1024} KB")

# promo video (for YouTube): landscape, plays, has audio
p = D / "promo-video-ar.mp4"
if p.exists():
    info = json.loads(subprocess.run(["ffprobe", "-v", "error", "-show_streams", "-show_format", "-of", "json", str(p)],
                                     capture_output=True, text=True, check=True).stdout)
    v = next(s for s in info["streams"] if s["codec_type"] == "video")
    a = [s for s in info["streams"] if s["codec_type"] == "audio"]
    dur = float(info["format"]["duration"])
    check(p.name, int(v["width"]) == 1920 and int(v["height"]) == 1080 and bool(a) and dur <= 120,
          f"{v['width']}×{v['height']} {v['codec_name']} {eval(v['r_frame_rate']):g} fps, audio {a[0]['codec_name'] if a else 'none'}, {dur:.1f} s, {p.stat().st_size / 1e6:.1f} MB")
else:
    check("promo-video-ar.mp4", False, "missing")

srt = D / "captions-ar.srt"
check(srt.name, srt.exists() and srt.read_text(encoding="utf-8").count("-->") > 0, "Arabic captions for the YouTube upload")

report = ["# Google Play asset spec check (generated by scripts/store-verify.py)", "",
          "| Asset | Measured | Result |", "|---|---|---|", *rows, ""]
(D / "spec-check.md").write_text("\n".join(report) + "\n", encoding="utf-8")
print("\n".join(report))
sys.exit(0 if ok_all else 1)
